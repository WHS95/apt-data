export interface 단지_추천_옵션 {
  시도_코드_목록: string[];
  시군구_코드_목록?: string[];
  물건_유형들: 물건_유형_코드[];
  면적_구간?: 면적_구간_코드 | "전체";
  면적_최소_제곱미터?: number;
  면적_최대_제곱미터?: number;
  건축_연도_최소?: number;
  건축_연도_최대?: number;
  예산_상한_만원?: number;
  예산_하한_만원?: number;
  카테고리?: 추천_카테고리;
  기간_개월?: number;
  최대?: number;
  최소_거래_건수?: number;
  정렬?:
    | "추천순"
    | "갭낮은순"
    | "갭높은순"
    | "평당가낮은순"
    | "평당가높은순"
    | "최신거래가높은순"
    | "상승률높은순";
}

const 일자_뒤로 = (기준: Date, 일수: number): string => {
  const d = new Date(기준);
  d.setDate(d.getDate() - 일수);
  return d.toISOString().slice(0, 10);
};

const 점수_가성비_계산 = (가성비_퍼센트: number | null): number => {
  if (가성비_퍼센트 == null) return 50;
  // 가성비 = (시군구평균 - 단지평균) / 시군구평균 × 100
  // +20%(많이 저렴)=100, 0%=50, -20%(많이 비쌈)=0
  return Math.max(0, Math.min(100, 50 + 가성비_퍼센트 * 2.5));
};

const 점수_모멘텀_계산 = (변화_6개월: number | null): number => {
  if (변화_6개월 == null) return 50;
  if (변화_6개월 < -5) return 25;
  if (변화_6개월 < 0) return 50;
  if (변화_6개월 <= 8) return 100 - Math.abs(변화_6개월 - 5) * 5;
  if (변화_6개월 <= 15) return 80 - (변화_6개월 - 8) * 4;
  return 40; // 과열
};

const 점수_유동성_계산 = (거래_건수: number): number => {
  if (거래_건수 >= 50) return 100;
  if (거래_건수 >= 30) return 85;
  if (거래_건수 >= 15) return 70;
  if (거래_건수 >= 8) return 55;
  return 30;
};

const 점수_안정성_계산 = (전세가율: number | null): number => {
  if (전세가율 == null) return 50;
  // 70% 만점, ±10%마다 감점
  return Math.max(0, Math.min(100, 100 - Math.abs(전세가율 - 70) * 4));
};

const 점수_신축도_계산 = (건축_연도: number | null): number => {
  if (!건축_연도) return 40;
  const 나이 = 2026 - 건축_연도;
  if (나이 <= 5) return 100;
  if (나이 <= 10) return 85;
  if (나이 <= 20) return 65;
  if (나이 <= 30) return 45;
  return 25;
};

const 가중치: Record<추천_카테고리, [number, number, number, number, number]> = {
  종합:   [0.25, 0.25, 0.20, 0.20, 0.10],
  가성비: [0.55, 0.10, 0.15, 0.15, 0.05],
  모멘텀: [0.15, 0.50, 0.15, 0.10, 0.10],
  안정성: [0.15, 0.10, 0.20, 0.45, 0.10],
  신축:   [0.15, 0.15, 0.10, 0.15, 0.45],
};

const 강점_생성 = (행: 단지_추천_행): string[] => {
  const 결과: string[] = [];
  if (행.가성비_퍼센트 != null && 행.가성비_퍼센트 >= 5)
    결과.push(`시군구 평균보다 ${행.가성비_퍼센트.toFixed(0)}% 저렴`);
  if (행.변화_6개월_퍼센트 != null && 행.변화_6개월_퍼센트 >= 2 && 행.변화_6개월_퍼센트 <= 12)
    결과.push(`6개월 +${행.변화_6개월_퍼센트.toFixed(1)}% 상승`);
  if (행.거래_건수 >= 20)
    결과.push(`최근 1년 거래 ${행.거래_건수}건 (활발)`);
  if (행.전세가율_퍼센트 != null && 행.전세가율_퍼센트 >= 60 && 행.전세가율_퍼센트 <= 75)
    결과.push(`전세가율 ${행.전세가율_퍼센트.toFixed(0)}% (안정 구간)`);
  if (행.건축_연도 && 행.건축_연도 >= 2018)
    결과.push(`${행.건축_연도}년 준공 (신축)`);
  return 결과.slice(0, 3);
};

const 약점_생성 = (행: 단지_추천_행): string[] => {
  const 결과: string[] = [];
  if (행.가성비_퍼센트 != null && 행.가성비_퍼센트 <= -10)
    결과.push(`시군구 평균보다 ${Math.abs(행.가성비_퍼센트).toFixed(0)}% 비쌈`);
  if (행.변화_6개월_퍼센트 != null && 행.변화_6개월_퍼센트 <= -3)
    결과.push(`6개월 ${행.변화_6개월_퍼센트.toFixed(1)}% 하락`);
  if (행.변화_6개월_퍼센트 != null && 행.변화_6개월_퍼센트 >= 15)
    결과.push(`6개월 +${행.변화_6개월_퍼센트.toFixed(1)}% 과열`);
  if (행.거래_건수 < 8)
    결과.push(`거래 ${행.거래_건수}건 (희소)`);
  if (행.전세가율_퍼센트 != null && 행.전세가율_퍼센트 >= 80)
    결과.push(`전세가율 ${행.전세가율_퍼센트.toFixed(0)}% (깡통전세 위험)`);
  if (행.건축_연도 && 행.건축_연도 < 1995)
    결과.push(`${행.건축_연도}년 준공 (구축)`);
  return 결과.slice(0, 3);
};

export class 단지_추천_유스케이스 {
  async 실행(옵션: 단지_추천_옵션): Promise<단지_추천_행[]> {
    const 카테고리 = 옵션.카테고리 ?? "종합";
    const 기간_개월 = 옵션.기간_개월 ?? 6;
    const 최소_건수 =
      옵션.최소_거래_건수 ??
      (기간_개월 <= 1 ? 1 :
       기간_개월 <= 3 ? 3 :
       기간_개월 <= 6 ? 5 :
       기간_개월 <= 12 ? 8 : 12);
    const 오늘 = new Date();
    const 기간_일 = 기간_개월 * 30;
    const T_90 = 일자_뒤로(오늘, Math.floor(기간_일 / 2));
    const T_180 = 일자_뒤로(오늘, 기간_일);
    const T_270 = 일자_뒤로(오늘, 기간_일 + Math.floor(기간_일 / 2));
    const T_365 = 일자_뒤로(오늘, 기간_일 * 2);

    const 공통_절들 = [
      inArray(실거래_테이블.시도_코드, 옵션.시도_코드_목록),
      inArray(실거래_테이블.물건_유형, 옵션.물건_유형들),
      eq(실거래_테이블.해제_여부, false),
      gte(실거래_테이블.계약_일자, T_365),
      sql`${실거래_테이블.단지명} IS NOT NULL AND ${실거래_테이블.단지명} <> ''`,
    ];
    if (옵션.시군구_코드_목록 && 옵션.시군구_코드_목록.length > 0) {
      공통_절들.push(inArray(실거래_테이블.시군구_코드, 옵션.시군구_코드_목록));
    }

    if (옵션.면적_최소_제곱미터 != null) {
      공통_절들.push(gte(실거래_테이블.전용_면적_제곱미터, 옵션.면적_최소_제곱미터));
    }
    if (옵션.면적_최대_제곱미터 != null) {
      공통_절들.push(lte(실거래_테이블.전용_면적_제곱미터, 옵션.면적_최대_제곱미터));
    }
    if (옵션.건축_연도_최소 != null) {
      공통_절들.push(gte(실거래_테이블.건축_연도, 옵션.건축_연도_최소));
    }
    if (옵션.건축_연도_최대 != null) {
      공통_절들.push(lte(실거래_테이블.건축_연도, 옵션.건축_연도_최대));
    }
    if (옵션.예산_하한_만원 != null) {
      공통_절들.push(gte(실거래_테이블.거래_금액_만원, 옵션.예산_하한_만원));
    }
    if (옵션.면적_구간 && 옵션.면적_구간 !== "전체") {
      const 구간 = 면적_구간[옵션.면적_구간];
      공통_절들.push(gte(실거래_테이블.전용_면적_제곱미터, 구간.최소));
      if (Number.isFinite(구간.최대)) {
        공통_절들.push(lte(실거래_테이블.전용_면적_제곱미터, 구간.최대));
      }
    }

    // 단지별 집계 (시도+시군구+단지명+물건유형 키)
    const 단지_집계 = await DB.select({
      시도_코드: 실거래_테이블.시도_코드,
      시도명: 시도_테이블.이름,
      시군구_코드: 실거래_테이블.시군구_코드,
      시군구명: 시군구_테이블.이름,
      단지명: 실거래_테이블.단지명,
      물건_유형: 실거래_테이블.물건_유형,
      평균_면적: sql<number>`avg(${실거래_테이블.전용_면적_제곱미터})::real`,
      건축_연도: sql<number>`max(${실거래_테이블.건축_연도})::int`,
      현재_평균가: sql<number>`
        avg(CASE
          WHEN ${실거래_테이블.거래_유형} = '1' AND ${실거래_테이블.계약_일자} > ${T_180}
          THEN ${실거래_테이블.거래_금액_만원} END)::int
      `,
      과거_평균가: sql<number>`
        avg(CASE
          WHEN ${실거래_테이블.거래_유형} = '1'
          AND ${실거래_테이블.계약_일자} > ${T_365}
          AND ${실거래_테이블.계약_일자} <= ${T_270}
          THEN ${실거래_테이블.거래_금액_만원} END)::int
      `,
      전세_평균: sql<number>`
        avg(CASE
          WHEN ${실거래_테이블.거래_유형} = '2'
          AND ${실거래_테이블.계약_일자} > ${T_180}
          THEN ${실거래_테이블.보증금_만원} END)::int
      `,
      거래_건수: sql<number>`count(*)::int`,
    })
      .from(실거래_테이블)
      .leftJoin(시군구_테이블, eq(시군구_테이블.코드, 실거래_테이블.시군구_코드))
      .leftJoin(시도_테이블, eq(시도_테이블.코드, 실거래_테이블.시도_코드))
      .where(and(...공통_절들))
      .groupBy(
        실거래_테이블.시도_코드,
        시도_테이블.이름,
        실거래_테이블.시군구_코드,
        시군구_테이블.이름,
        실거래_테이블.단지명,
        실거래_테이블.물건_유형,
      )
      .having(sql`count(*) >= ${최소_건수}`);

    // 시군구별 평균가 (가성비 비교용)
    const 시군구_평균 = await DB.select({
      시군구_코드: 실거래_테이블.시군구_코드,
      평균: sql<number>`avg(${실거래_테이블.거래_금액_만원})::int`,
    })
      .from(실거래_테이블)
      .where(
        and(
          ...공통_절들,
          eq(실거래_테이블.거래_유형, "1"),
          gte(실거래_테이블.계약_일자, T_180),
        ),
      )
      .groupBy(실거래_테이블.시군구_코드);
    const 시군구_맵 = new Map(시군구_평균.map((s) => [s.시군구_코드, s.평균]));

    // 단지별 매매 거래 전체 조회 (정상 최신 거래 추출용)
    const 매매_거래들 = await DB.select({
      시군구_코드: 실거래_테이블.시군구_코드,
      단지명: 실거래_테이블.단지명,
      계약_일자: 실거래_테이블.계약_일자,
      거래_금액_만원: 실거래_테이블.거래_금액_만원,
      거래_경위: 실거래_테이블.거래_경위,
    })
      .from(실거래_테이블)
      .where(and(...공통_절들, eq(실거래_테이블.거래_유형, "1")));

    // 단지별 그룹핑 → 중위 ±35% 안 + 직거래 아닌 거래 → 최신 1건
    const 단지_매매_맵 = new Map<
      string,
      Array<{ 계약_일자: string; 거래_금액_만원: number; 거래_경위: string | null }>
    >();
    for (const r of 매매_거래들) {
      if (!r.거래_금액_만원 || !r.단지명) continue;
      const 키 = `${r.시군구_코드}|${r.단지명}`;
      if (!단지_매매_맵.has(키)) 단지_매매_맵.set(키, []);
      단지_매매_맵.get(키)!.push({
        계약_일자: r.계약_일자,
        거래_금액_만원: r.거래_금액_만원,
        거래_경위: r.거래_경위 ?? null,
      });
    }
    const 최신_정상_거래_맵 = new Map<
      string,
      { 거래가: number; 일자: string; 정상_거래_건수: number }
    >();
    // 신뢰도 지표(직거래 비율·이상치 건수)는 정상 최신 유무와 무관하게 계산 → 별도 맵
    const 신뢰도_맵 = new Map<
      string,
      { 직거래_비율: number; 이상치_건수: number }
    >();
    for (const [키, 거래들] of 단지_매매_맵.entries()) {
      const 가격들 = 거래들.map((d) => d.거래_금액_만원);
      const 정렬됨 = [...가격들].sort((a, b) => a - b);
      const 중위 = 정렬됨[Math.floor(정렬됨.length / 2)];

      // 직거래 비율: 전체 매매 대비 거래_경위='직거래' 비율(%)
      const 직거래_수 = 거래들.filter((d) => d.거래_경위 === "직거래").length;
      // 이상치: 중위 ±35% 밴드를 벗어난 매매 건수(직거래 여부와 무관, 밴드 단독)
      const 이상치_수 = 거래들.filter(
        (d) => d.거래_금액_만원 < 중위 * 0.65 || d.거래_금액_만원 > 중위 * 1.35,
      ).length;
      신뢰도_맵.set(키, {
        직거래_비율: Math.round((직거래_수 / 거래들.length) * 100),
        이상치_건수: 이상치_수,
      });

      const 정상 = 거래들.filter(
        (d) =>
          d.거래_경위 !== "직거래" &&
          d.거래_금액_만원 >= 중위 * 0.65 &&
          d.거래_금액_만원 <= 중위 * 1.35,
      );
      if (정상.length === 0) continue;
      const 최신 = 정상.reduce((a, b) =>
        a.계약_일자 > b.계약_일자 ? a : b,
      );
      최신_정상_거래_맵.set(키, {
        거래가: 최신.거래_금액_만원,
        일자: 최신.계약_일자,
        정상_거래_건수: 정상.length,
      });
    }

    // 월별 평균가 (sparkline)
    const 월별 = await DB.select({
      단지_키: sql<string>`${실거래_테이블.시군구_코드} || '|' || ${실거래_테이블.단지명}`,
      년월: sql<string>`to_char(${실거래_테이블.계약_일자}, 'YYYY-MM')`,
      평균: sql<number>`avg(${실거래_테이블.거래_금액_만원})::int`,
    })
      .from(실거래_테이블)
      .where(and(...공통_절들, eq(실거래_테이블.거래_유형, "1")))
      .groupBy(
        실거래_테이블.시군구_코드,
        실거래_테이블.단지명,
        sql`to_char(${실거래_테이블.계약_일자}, 'YYYY-MM')`,
      )
      .orderBy(sql`to_char(${실거래_테이블.계약_일자}, 'YYYY-MM')`);

    const 월별_맵 = new Map<string, Array<{ 년월: string; 평균_만원: number }>>();
    for (const m of 월별) {
      if (!월별_맵.has(m.단지_키)) 월별_맵.set(m.단지_키, []);
      월별_맵.get(m.단지_키)!.push({ 년월: m.년월, 평균_만원: m.평균 });
    }

    const [w1, w2, w3, w4, w5] = 가중치[카테고리];

    const 행들: 단지_추천_행[] = 단지_집계
      .filter((d) => d.현재_평균가 != null && (!옵션.예산_상한_만원 || d.현재_평균가 <= 옵션.예산_상한_만원))
      .map((d) => {
        const 시군구_avg = 시군구_맵.get(d.시군구_코드) ?? null;
        const 가성비_퍼센트 =
          시군구_avg && d.현재_평균가
            ? Math.round(((시군구_avg - d.현재_평균가) / 시군구_avg) * 1000) / 10
            : null;
        const 변화_6개월 =
          d.현재_평균가 && d.과거_평균가
            ? Math.round(((d.현재_평균가 - d.과거_평균가) / d.과거_평균가) * 1000) / 10
            : null;
        const 전세가율 =
          d.현재_평균가 && d.전세_평균
            ? Math.round((d.전세_평균 / d.현재_평균가) * 1000) / 10
            : null;

        const 점수_가성비 = 점수_가성비_계산(가성비_퍼센트);
        const 점수_모멘텀 = 점수_모멘텀_계산(변화_6개월);
        const 점수_유동성 = 점수_유동성_계산(d.거래_건수);
        const 점수_안정성 = 점수_안정성_계산(전세가율);
        const 점수_신축도 = 점수_신축도_계산(d.건축_연도);

        // 초소형 감점: 전용면적이 작을수록 종합 점수에 감점 계수 적용
        // (16~30㎡ 초소형이 상위권을 도배하는 문제 완화, 완전 배제는 아님)
        const 면적_계수 =
          d.평균_면적 != null && d.평균_면적 < 40
            ? 0.75
            : d.평균_면적 != null && d.평균_면적 < 50
              ? 0.9
              : 1.0;
        const 종합 = Math.round(
          (점수_가성비 * w1 +
            점수_모멘텀 * w2 +
            점수_유동성 * w3 +
            점수_안정성 * w4 +
            점수_신축도 * w5) *
            면적_계수,
        );

        const 최신_정상 = 최신_정상_거래_맵.get(`${d.시군구_코드}|${d.단지명}`);
        const 신뢰도 = 신뢰도_맵.get(`${d.시군구_코드}|${d.단지명}`);
        // 평당가: 최신 정상 거래가 / 평(1평=3.305785㎡). 면적 0 또는 정상 거래 없으면 null
        const 평당가 =
          최신_정상 && d.평균_면적 && d.평균_면적 > 0
            ? Math.round(최신_정상.거래가 / (d.평균_면적 / 3.305785))
            : null;
        // 갭: 현재 평균가 - 전세 평균(둘 다 있을 때)
        const 갭 =
          d.현재_평균가 != null && d.전세_평균 != null
            ? d.현재_평균가 - d.전세_평균
            : null;
        const 행_기본: 단지_추천_행 = {
          단지_키: `${d.시군구_코드}|${d.단지명}`,
          시도_코드: d.시도_코드,
          시도명: d.시도명 ?? d.시도_코드,
          시군구_코드: d.시군구_코드,
          시군구명: d.시군구명 ?? d.시군구_코드,
          단지명: d.단지명!,
          물건_유형: d.물건_유형 as 물건_유형_코드,
          평균_면적_제곱미터: d.평균_면적 ?? 0,
          건축_연도: d.건축_연도 ?? null,
          현재_평균가_만원: d.현재_평균가,
          최신_거래가_만원: 최신_정상?.거래가 ?? null,
          최신_거래일: 최신_정상?.일자 ?? null,
          전세_평균_만원: d.전세_평균,
          거래_건수: d.거래_건수,
          정상_거래_건수: 최신_정상?.정상_거래_건수 ?? 0,
          시군구_평균가_만원: 시군구_avg,
          가성비_퍼센트,
          변화_6개월_퍼센트: 변화_6개월,
          전세가율_퍼센트: 전세가율,
          평당가_만원: 평당가,
          갭_만원: 갭,
          직거래_비율: 신뢰도?.직거래_비율 ?? 0,
          이상치_건수: 신뢰도?.이상치_건수 ?? 0,
          점수_가성비: Math.round(점수_가성비),
          점수_모멘텀: Math.round(점수_모멘텀),
          점수_유동성: Math.round(점수_유동성),
          점수_안정성: Math.round(점수_안정성),
          점수_신축도: Math.round(점수_신축도),
          종합_점수: 종합,
          강점들: [],
          약점들: [],
          월별_평균가: 월별_맵.get(`${d.시군구_코드}|${d.단지명}`) ?? [],
        };
        행_기본.강점들 = 강점_생성(행_기본);
        행_기본.약점들 = 약점_생성(행_기본);
        return 행_기본;
      });

    // null은 항상 맨 뒤로: 오름차순이면 +Infinity, 내림차순이면 -Infinity로 치환
    const 널뒤 = (v: number | null, 오름차순: boolean): number =>
      v ?? (오름차순 ? Infinity : -Infinity);

    const 정렬 = 옵션.정렬 ?? "추천순";
    switch (정렬) {
      case "갭낮은순":
        행들.sort((a, b) => 널뒤(a.갭_만원, true) - 널뒤(b.갭_만원, true));
        break;
      case "갭높은순":
        행들.sort((a, b) => 널뒤(b.갭_만원, false) - 널뒤(a.갭_만원, false));
        break;
      case "평당가낮은순":
        행들.sort((a, b) => 널뒤(a.평당가_만원, true) - 널뒤(b.평당가_만원, true));
        break;
      case "평당가높은순":
        행들.sort((a, b) => 널뒤(b.평당가_만원, false) - 널뒤(a.평당가_만원, false));
        break;
      case "최신거래가높은순":
        행들.sort(
          (a, b) => 널뒤(b.최신_거래가_만원, false) - 널뒤(a.최신_거래가_만원, false),
        );
        break;
      case "상승률높은순":
        행들.sort(
          (a, b) =>
            널뒤(b.변화_6개월_퍼센트, false) - 널뒤(a.변화_6개월_퍼센트, false),
        );
        break;
      default: // "추천순"
        행들.sort((a, b) => b.종합_점수 - a.종합_점수);
    }

    return 행들.slice(0, 옵션.최대 ?? 30);
  }
}
